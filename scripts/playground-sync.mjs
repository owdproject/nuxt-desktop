#!/usr/bin/env node
/**
 * Centralized playground sync for OWD Nuxt extension packages.
 *
 * One source of truth for the demo set (presets) -> generates, idempotently:
 *   - playground/presets/<preset>.ts   (data only)
 *   - playground/desktop.config.ts     (self extension + preset)
 *   - playground/package.json          (demo deps, private)
 *   - pnpm-workspace.yaml              (standalone CI workspace)
 *   - .github/workflows/pages.yml      (GitHub Pages demo)
 *
 * Demo apps live ONLY in the playground (private, not in `files`), so installing
 * the theme/app never pulls demo packages.
 *
 * Usage: node scripts/playground-sync.mjs [pkgDir ...]
 *        (default: every themes/* package that has a playground)
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execSync } from 'node:child_process'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/** Version pinned across every generated playground. */
const ALPHA = '4.0.0-alpha.3'

/**
 * Central demo sets. Change here -> every theme playground updates.
 * Keep it "showcase"-safe: only extensions that need no extra modules.
 */
export const PRESETS = {
  nuxt: {
    showcase: {
      modules: [
        '@owdproject/nuxt-module-pinia-persistence',
        '@owdproject/nuxt-module-fs',
      ],
      apps: [
        '@owdproject/nuxt-app-about',
        '@owdproject/nuxt-app-classic-audioplayer',
        '@owdproject/nuxt-app-classic-videoplayer',
        '@owdproject/nuxt-app-debug',
        '@owdproject/nuxt-app-dino',
        '@owdproject/nuxt-app-gridsky',
        '@owdproject/nuxt-app-slowroads',
        '@owdproject/nuxt-app-soundcloud',
        '@owdproject/nuxt-app-terminal',
        '@owdproject/nuxt-app-todo',
        '@owdproject/nuxt-app-twitch-chat',
        '@owdproject/nuxt-app-wasmboy',
        '@owdproject/nuxt-app-youtube',
      ],
    },
  },
}

const WORKSPACE = `packages:
  - 'playground'
allowBuilds:
  esbuild: true
  '@parcel/watcher': true
  '@swc/core': true
  unrs-resolver: true
  core-js: true
  "audiobuffer-to-wav@https://codeload.github.com/torch2424/audiobuffer-to-wav/tar.gz/8878a20c5cc7e457b113dabfb1781ad4178f9c62": true
blockExoticSubdeps: false
minimumReleaseAge: 0
`

function pagesYml(repo) {
  return `name: Deploy playground to GitHub Pages

on:
  push:
    branches:
      - main
  workflow_dispatch:

permissions:
  contents: read
  pages: write
  id-token: write

concurrency:
  group: pages
  cancel-in-progress: true

jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      - uses: actions/setup-node@v4
        with:
          node-version: 22

      - name: Setup Pages
        uses: actions/configure-pages@v5
        with:
          enablement: true

      - run: npm i -g --force corepack@latest && corepack enable

      - name: Install dependencies
        run: pnpm install --no-frozen-lockfile

      - name: Prepare module and playground
        run: pnpm run dev:prepare

      - name: Generate static playground
        run: pnpm run dev:generate
        env:
          NUXT_APP_BASE_URL: /${repo}/

      - name: Upload Pages artifact
        uses: actions/upload-pages-artifact@v3
        with:
          path: playground/.output/public

  deploy:
    needs: build
    environment:
      name: github-pages
      url: \${{ steps.deployment.outputs.page_url }}
    runs-on: ubuntu-latest
    steps:
      - name: Deploy to GitHub Pages
        id: deployment
        uses: actions/deploy-pages@v4
`
}

function presetFile(preset) {
  return `// AUTO-GENERATED by scripts/playground-sync.mjs — do not edit by hand.
// Demo set only: used by this playground, never shipped with the package.
export default {
  modules: ${JSON.stringify(preset.modules, null, 2).replace(/\n/g, '\n  ')},
  apps: ${JSON.stringify(preset.apps, null, 2).replace(/\n/g, '\n  ')},
}
`
}

function desktopConfig(selfPkg, presetName) {
  return `import { defineDesktopConfig } from '@owdproject/nuxt'
import ${presetName} from './presets/${presetName}.ts'

export default defineDesktopConfig({
  theme: '${selfPkg}',
  ...${presetName},
})
`
}

function repoSlug(dir) {
  try {
    return execSync(`git -C ${JSON.stringify(dir)} remote get-url origin`, { encoding: 'utf8' })
      .trim()
      .replace(/\.git$/, '')
      .split(/[/:]/)
      .pop()
  } catch {
    return basename(dir)
  }
}

function syncTheme(dir, presetName = 'showcase') {
  const themePkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const pgDir = join(dir, 'playground')
  if (!existsSync(pgDir)) return null
  const preset = PRESETS.nuxt[presetName]
  const repo = repoSlug(dir)

  mkdirSync(join(pgDir, 'presets'), { recursive: true })
  writeFileSync(join(pgDir, 'presets', `${presetName}.ts`), presetFile(preset))
  writeFileSync(join(pgDir, 'desktop.config.ts'), desktopConfig(themePkg.name, presetName))

  const pg = JSON.parse(readFileSync(join(pgDir, 'package.json'), 'utf8'))
  const deps = {
    [themePkg.name]: 'workspace:*',
    '@owdproject/core': ALPHA,
    '@owdproject/nuxt': ALPHA,
    '@owdproject/nuxt-kit-primevue': ALPHA,
    '@owdproject/nuxt-kit-tailwind': ALPHA,
    'nuxt': '^4.6.2',
    'primevue': '^4.5.5',
    'vue-i18n': '^11.0.0',
  }
  for (const a of preset.apps) deps[a] = ALPHA
  for (const m of preset.modules) deps[m] = ALPHA
  pg.dependencies = Object.fromEntries(Object.entries(deps).sort(([a], [b]) => a.localeCompare(b)))
  pg.devDependencies = { 'jiti': '^2.6.1', 'tailwindcss': '^3.4.19' }
  writeFileSync(join(pgDir, 'package.json'), JSON.stringify(pg, null, 2) + '\n')

  writeFileSync(join(dir, 'pnpm-workspace.yaml'), WORKSPACE)
  mkdirSync(join(dir, '.github/workflows'), { recursive: true })
  writeFileSync(join(dir, '.github/workflows/pages.yml'), pagesYml(repo))

  return { dir, repo, theme: themePkg.name, apps: preset.apps.length }
}

const args = process.argv.slice(2)
const targets = args.length
  ? args.map((a) => join(root, a))
  : ['themes'].flatMap((base) => {
      const p = join(root, base)
      if (!existsSync(p)) return []
      return execSync(`ls ${p}`, { encoding: 'utf8' })
        .trim()
        .split('\n')
        .map((n) => join(p, n))
    })

const results = []
for (const dir of targets) {
  if (!existsSync(join(dir, 'package.json'))) continue
  const name = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).name || ''
  if (!name.startsWith('@owdproject/nuxt-theme-')) continue
  const r = syncTheme(dir)
  if (r) results.push(r)
}
for (const r of results) console.log(`synced ${r.theme}  repo=${r.repo}  apps=${r.apps}`)
console.log(`\n${results.length} theme playground(s) synced from central presets.`)
